#!/usr/bin/env bash
#
# E124 -- E117 again, FITTED ON THE 60-DAY LABEL and SCORED ON THE 20-DAY ONE.
#
# Same model, data and windows as E117: ridge_glmnet on allfeat_pp minus the
# tenc column (811 features), rolling training windows of 5 / 10 / 15 / 20 / 22
# / 65 / 130 periods (1, 2, 3, 4 weeks, 1, 3, 6 months), refit every 130,
# lambda SEARCHED FROM SCRATCH at every refit, windows under 130 tuned on the
# 130 periods ending where the window ends (--tune-window 130).
#
# What changes, and only because the label forces it:
#
#   --target target_binned_return_60   the model is fitted AND tuned on it
#   --embargo 60                       a 60-day forward return must sit 60
#                                      periods from anything it is scored on
#
# The DELIVERABLE is the 20-day RE-SCORE: each arm's predictions are graded on
# target_binned_return_20 by src.analysis.cross_target.score_on_payable_target,
# against the same meta model and reference every deployed slot is graded on.
# That is what Numerai pays. src.analysis.e124_report then puts all fourteen
# arms -- E117's seven fitted on 20, these seven fitted on 60 -- in ONE table on
# ONE common window.
#
# Three things the 60-day label costs, stated so nobody rediscovers them:
#
#   * TWO inner folds, not four. A 60-period embargo inside a 130-period tuning
#     block leaves validation slices only at periods 78 and 104. This is exactly
#     what production's own 60-day search does (CURUPIRA_05_60: window 130,
#     embargo 60), so it is kept for fidelity -- but lambda is chosen on half
#     the validation data E117 had.
#   * The panel SHRINKS. target_binned_return_60 is NaN over the last ~40
#     dates, so these arms cannot predict them; the consolidated table drops
#     those dates from the 20-day arms too, so every row shares one window.
#   * ~3x fewer effective independent windows on the fitted label, so the
#     report shows the paired t at Newey-West lag 20 (the scored label's
#     overlap) AND at lag 60 (E60's conservative choice).
#
# Placement (cluster-job-placement): ridge wants an 8-core slot, but at launch
# no box offered more than 3 cores at the 30% share. So four 3-core slots, with
# --search-jobs 3 x --n-jobs 1 = the slot, and three slots running two arms
# back to back (';' not '&&', so one arm failing does not cost its neighbour).
# Reruns place one job per MISSING arm instead.
#
# Usage:
#   bash experiments/e124_train_window_t60_crypto.sh          # plan + run
#   DRY_RUN=1 bash experiments/e124_train_window_t60_crypto.sh   # plan only
#
set -uo pipefail
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO"
mkdir -p logs

SLOT="${T60_SLOT_CORES:-3}"
DATA="crypto/v2.0-tenc-onehot-rollsel-spread-interact"
JOBS="logs/e124_jobs.txt"

arm() {   # the command for one arm, as a single shell string
    local window="$1" tune=""
    [ "${window}" -lt 130 ] && tune="--tune-window 130"
    printf "python3 -u -m src.run_forecast crypto ridge_glmnet --task regression --metric corr --bmc-reference benchmark --target target_binned_return_60 --cv-scheme rolling --train-window %s %s --refit-every 130 --embargo 60 --n-splits 5 --n-iter 50 --seed 42 --val-frac 0.3 --n-jobs 1 --search-jobs %s --data-version %s --feature-exclude '^feature_sym_tenc\$' --run-name e124_w%s > logs/e124_w%s.log 2>&1" \
        "${window}" "${tune}" "${SLOT}" "${DATA}" "${window}" "${window}"
}

# RESUMABLE: one job per arm whose metrics json is not on disk yet, so a rerun
# after a failure relaunches only what is missing. The first launch lost five of
# seven arms to a full /home quota (Errno 122, no traceback -- the write itself
# failed); this is how the survivors were kept.
{
  echo "# generated by experiments/e124_train_window_t60_crypto.sh -- edit that, not this"
  for window in 130 65 22 20 15 10 5; do
      if [ -f "results/metrics/crypto/ridge_glmnet/e124_w${window}.json" ]; then
          echo "# e124_w${window} already finished -- skipped"
          continue
      fi
      echo "cores=${SLOT} ram=16 name=e124_w${window} -- $(arm "${window}")"
  done
} > "${JOBS}"
grep -q '^cores=' "${JOBS}" || { echo "every E124 arm has finished; nothing to launch"; exit 0; }

python3 -m src.cluster plan --jobs "${JOBS}" || exit 1
[ "${DRY_RUN:-0}" = "1" ] && exit 0
python3 -m src.cluster run --jobs "${JOBS}"
